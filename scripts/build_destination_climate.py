"""Monthly climate for every Where-next destination, baked into the app (ios/Trippy/DestinationClimate.swift).

For each place in ios/Trippy/Destinations.swift: average daytime high (°C), snowfall (cm a month) and rainy days
(>= 1 mm) per month, averaged over 2022-2024 from the Open-Meteo archive (ERA5 reanalysis, CC BY 4.0).
Run once when the catalog changes; the app never calls a weather service.

    python scripts/build_destination_climate.py            # fetch what is missing, write the Swift file
"""
import json
import re
import sys
import time
import urllib.parse
import urllib.request
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'ios/Trippy/Destinations.swift'
CACHE = ROOT / '.local/destination-climate.json'
OUT = ROOT / 'ios/Trippy/DestinationClimate.swift'


def destinations():
    rows = re.findall(r'^\s{4}([^|\n]+)\|([A-Z]{2})\|(-?[\d.]+)\|(-?[\d.]+)\|', CATALOG.read_text(encoding='utf-8'), re.M)
    return [(name, code, float(lat), float(lon)) for name, code, lat, lon in rows]


def fetch(lat, lon):
    query = urllib.parse.urlencode({'latitude': lat, 'longitude': lon, 'start_date': '2022-01-01', 'end_date': '2024-12-31',
                                    'daily': 'temperature_2m_max,snowfall_sum,precipitation_sum', 'timezone': 'UTC'})
    with urllib.request.urlopen('https://archive-api.open-meteo.com/v1/archive?' + query, timeout=60) as reply:
        daily = json.load(reply)['daily']
    high, snow, wet, days = defaultdict(list), defaultdict(float), defaultdict(int), defaultdict(int)
    for day, t, s, p in zip(daily['time'], daily['temperature_2m_max'], daily['snowfall_sum'], daily['precipitation_sum']):
        month = int(day[5:7])
        days[month] += 1
        if t is not None: high[month].append(t)
        snow[month] += s or 0
        wet[month] += (p or 0) >= 1
    return {'high': [round(sum(high[m]) / max(1, len(high[m]))) for m in range(1, 13)],
            'snow': [round(snow[m] / 3) for m in range(1, 13)],                      # cm in an average month
            'wet': [round(wet[m] / days[m] * 30) for m in range(1, 13)]}             # rainy days in a 30-day month


def main():
    known = json.loads(CACHE.read_text()) if CACHE.exists() else {}
    places = destinations()
    for index, (name, code, lat, lon) in enumerate(places):
        key = f'{name}|{code}'
        if key in known: continue
        for attempt in range(6):
            try:
                known[key] = fetch(lat, lon); break
            except Exception as error:  # noqa: BLE001 - the free archive allows a limited number of requests a minute
                print('waiting a minute:', key, type(error).__name__, file=sys.stderr); time.sleep(65)
        CACHE.parent.mkdir(parents=True, exist_ok=True); CACHE.write_text(json.dumps(known))
        print(f'{index + 1}/{len(places)} {key}', flush=True)
        time.sleep(1.5)
    missing = [f'{n}|{c}' for n, c, *_ in places if f'{n}|{c}' not in known]
    if missing: sys.exit('missing: ' + ', '.join(missing))
    lines = [f"    {n}|{c}|{','.join(map(str, known[f'{n}|{c}']['high']))}|{','.join(map(str, known[f'{n}|{c}']['snow']))}|{','.join(map(str, known[f'{n}|{c}']['wet']))}"
             for n, c, *_ in places]
    OUT.write_text('''import Foundation

// Generated by scripts/build_destination_climate.py. Do not edit by hand.
// Monthly averages for 2022-2024 from the Open-Meteo archive (ERA5 reanalysis, CC BY 4.0): typical weather, not a forecast.

/// What a month is usually like in a destination.
struct MonthClimate: Equatable {
    /// Average daytime high, °C.
    let high: Int
    /// Snowfall in an average month, cm.
    let snow: Int
    /// Days with at least 1 mm of rain or snow.
    let wetDays: Int
}

enum DestinationClimate {
    /// Destination id ("name|country") → twelve months, January first.
    static let table: [String: [MonthClimate]] = {
        var out: [String: [MonthClimate]] = [:]
        for line in rows.split(separator: "\\n") {
            let f = line.trimmingCharacters(in: .whitespaces).split(separator: "|").map(String.init)
            guard f.count == 5 else { continue }
            let high = f[2].split(separator: ",").compactMap { Int($0) }, snow = f[3].split(separator: ",").compactMap { Int($0) }
            let wet = f[4].split(separator: ",").compactMap { Int($0) }
            guard high.count == 12, snow.count == 12, wet.count == 12 else { continue }
            out[f[0] + "|" + f[1]] = (0..<12).map { MonthClimate(high: high[$0], snow: snow[$0], wetDays: wet[$0]) }
        }
        return out
    }()

    // name|country|daytime high per month|snow cm per month|wet days per month
    private static let rows = """
''' + '\n'.join(lines) + '\n    """\n}\n', encoding='utf-8')
    print('wrote', OUT.relative_to(ROOT), len(lines), 'places')


if __name__ == '__main__':
    main()
