"""Safe pipeline diagnostics: never copy exception bodies, prompts or credentials."""
import re
from trippy.sources.luna import BudgetError, ProviderConfigurationError, TransientProviderError


class ResearchProviderError(ValueError):
    def __init__(self, stage, kind, *, http_status=None, parameter=None, reason=None):
        self.stage=stage
        self.kind=kind
        self.http_status=http_status
        self.parameter=parameter
        self.reason=reason
        super().__init__(kind)


def failure_details(exc, *, task, stage):
    status=getattr(exc,'http_status',None) or getattr(exc,'status_code',None)
    status=status if type(status) is int and 100 <= status <= 599 else None
    code=getattr(exc,'kind',None) if isinstance(exc,(ResearchProviderError,TransientProviderError)) else None
    if isinstance(exc,BudgetError): code='budget_unavailable'
    elif isinstance(exc,ProviderConfigurationError): code='provider_configuration_required'
    elif status in {400,401,403,404,422}: code='provider_request_rejected'
    elif status in {408,429,500,502,503,504}: code='provider_temporarily_unavailable'
    elif isinstance(exc,(TimeoutError,ConnectionError)): code='provider_connection_failed'
    elif isinstance(exc,OSError): code='storage_unavailable'
    elif isinstance(exc,ValueError) and not code: code='research_validation_failed'
    if code not in {'budget_unavailable','provider_configuration_required','provider_request_rejected',
            'provider_temporarily_unavailable','provider_connection_failed','storage_unavailable',
            'research_validation_failed','web_response_incomplete','web_response_empty',
            'web_request_failed','sdk_incompatible','timeout','rate_limit','service_unavailable'}:
        code='research_failed'
    result={'task':task,'stage':getattr(exc,'stage',stage) if isinstance(exc,ResearchProviderError) else stage,
            'error_type':type(exc).__name__,'code':code}
    if status is not None: result['http_status']=status
    parameter=getattr(exc,'parameter',None)
    if parameter in {'conversation','model','max_output_tokens','max_tool_calls','api-version',
            'agent_reference','reasoning_effort','response_format','max_completion_tokens'}:
        result['parameter']=parameter
    reason=getattr(exc,'reason',None)
    if reason in {'max_output_tokens','content_filter'}: result['reason']=reason
    # These prefixes are generated by local validators, not provider bodies.
    if type(exc) is ValueError:
        match=re.fullmatch(r'(Invalid field|Invalid enum|Missing/unknown fields): ([A-Za-z0-9_$\.\[\]-]{1,120})',str(exc))
        if match: result['field_path']=match.group(2)
    return result
